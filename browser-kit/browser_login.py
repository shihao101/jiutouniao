#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
browser_login.py — 真实浏览器合规登录与会话捕获（九头鸟 browser-kit，v2.8.0 固化）

用途：当登录通道为 JS/WASM 加密、动态挑战 token、验证码渲染或 UA 指纹过滤时，
放弃 curl 明文构造，改由 Playwright 驱动系统 Chromium 以真实浏览器完成登录，
并一次性抓取「CLI 接管」所需的全部会话材料（browser-auth 技能的标准流水线第一步）。

设计纪律（与 ROE 对齐）：
  - 凭据只经环境变量注入（--password-env），不进 argv、不进日志；HAR 自动脱敏
  - 对目标流量默认剥离代理环境变量（直连），--proxy 仅限特殊链路显式开启
  - 串行限速（--interval-sec 默认 2s）、全局看门狗（--global-timeout 默认 240s < 引擎 300s）
  - 验证码人机协同：可见验证码且未提供 --captcha 时截图并以 exit 42 退出，
    由智能体 request_user_input 转人工读码——本工具不做自动打码
  - 自签名证书默认放行（ignore_https_errors），UA 默认真实 Chromium、可 --ua 钉住指纹

产物（全部落盘 --out 目录，供证据链 EV 编号引用）：
  cookies.txt(Netscape，可直接喂 curl -b) / cookies.json / storage.json(localStorage+sessionStorage)
  postlogin.html(登录后页面源码) / postlogin-links.txt(菜单与 API 端点候选清单)
  network.har(全流量，密码已脱敏) / shots/login.png shots/postlogin.png / summary.json

退出码：0 成功 | 1 用法/凭据缺失 | 2 导航/加载失败 | 3 登录未确认 | 42 需人工读验证码 | 45 多步登录需 OTP 口令

示例：
  JT_PASS='xxx' /opt/venv/bin/python /opt/tools/browser-kit/browser_login.py \
      --url https://10.0.0.1/index.html --user testuser \
      --password-env JT_PASS --success-marker 系统首页 \
      --out evidence/browser-login
  # 多步登录（MFA）：提交后出现口令输入位时自动注入（口令值经环境变量）
  JT_PASS='xxx' JT_OTP='123456' /opt/venv/bin/python /opt/tools/browser-kit/browser_login.py \
      --url https://10.0.0.1/index.html --user testuser \
      --password-env JT_PASS --otp-env JT_OTP \
      --out evidence/browser-login
"""
import argparse
import json
import os
import re
import shutil
import sys
import time
from pathlib import Path

EXIT_OK, EXIT_USAGE, EXIT_NAV, EXIT_LOGIN, EXIT_CAPTCHA, EXIT_OTP = 0, 1, 2, 3, 42, 45
PROXY_KEYS = ("http_proxy", "https_proxy", "HTTP_PROXY", "HTTPS_PROXY",
              "all_proxy", "ALL_PROXY", "ftp_proxy", "FTP_PROXY")


def log(msg):
    print(msg, file=sys.stderr, flush=True)


def scrub(text, secrets):
    for s in secrets:
        if s:
            text = text.replace(s, "***REDACTED***")
    return text


def detect_browser_path():
    p = os.environ.get("JT_BROWSER_PATH")
    if p and Path(p).exists():
        return p
    for name in ("chromium", "chromium-browser", "google-chrome", "google-chrome-stable"):
        w = shutil.which(name)
        if w:
            return w
    return None


def write_netscape(cookies, path):
    lines = ["# Netscape HTTP Cookie File", "# Generated by browser_login.py (jiutouniao browser-kit)"]
    for c in cookies:
        exp = int(c.get("expires") or 0)
        lines.append("\t".join([
            c.get("domain", ""), "TRUE" if c.get("domain", "").startswith(".") else "FALSE",
            c.get("path", "/"), "TRUE" if c.get("secure") else "FALSE",
            str(exp if exp > 0 else 0), c.get("name", ""), c.get("value", "")]))
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


# 选择器自动探测：在页面内执行，返回可见表单元素的唯一 CSS 路径
DETECT_JS = r"""
() => {
  function visible(el) {
    if (!el || el.type === 'hidden') return false;
    const r = el.getBoundingClientRect();
    const st = getComputedStyle(el);
    return r.width > 0 && r.height > 0 && st.visibility !== 'hidden' && st.display !== 'none';
  }
  function cssPath(el) {
    if (!(el instanceof Element)) return null;
    const parts = [];
    while (el && el.nodeType === 1 && parts.length < 8) {
      let sel = el.nodeName.toLowerCase();
      if (el.id) { parts.unshift(sel + '#' + CSS.escape(el.id)); break; }
      if (el.name) sel += '[name="' + el.name + '"]';
      const parent = el.parentNode;
      if (parent) {
        const sib = Array.from(parent.children).filter(c => c.nodeName === el.nodeName);
        if (sib.length > 1) sel += ':nth-of-type(' + (sib.indexOf(el) + 1) + ')';
      }
      parts.unshift(sel); el = parent;
    }
    return parts.join(' > ');
  }
  const inputs = Array.from(document.querySelectorAll('input')).filter(visible);
  const pass = inputs.find(i => i.type === 'password') || null;
  const codeRe = /code|captcha|verif|yzm|validate|验证码/i;
  const code = inputs.find(i => i !== pass && codeRe.test((i.name||'') + (i.id||'') + (i.placeholder||''))) || null;
  const scope = (pass && pass.form) || document;
  const textInputs = Array.from(scope.querySelectorAll('input')).filter(i =>
    visible(i) && i !== pass && i !== code && ['text','email','tel',''].includes(i.type));
  const userRe = /user|name|account|email|login|uid|member/i;
  const user = textInputs.find(i => userRe.test((i.name||'') + (i.id||'') + (i.placeholder||'')))
            || textInputs[0] || null;
  let submit = null;
  const buttons = Array.from(scope.querySelectorAll('button, input[type=submit], a')).filter(visible);
  submit = buttons.find(b => (b.type === 'submit')) ||
           buttons.find(b => /^(登录|log\s*in|sign\s*in|login)$/i.test((b.innerText || b.value || '').trim())) ||
           buttons.find(b => /登录|login/i.test((b.innerText || b.value || '').trim())) || null;
  return { user: cssPath(user), pass: cssPath(pass), code: cssPath(code),
           submit: cssPath(submit), codeVisible: !!(code && visible(code)),
           title: document.title, url: location.href };
}
"""

LINKS_JS = r"""
() => {
  const out = [];
  document.querySelectorAll('a[href], button[onclick], [ng-href], [ui-sref]').forEach(el => {
    const t = (el.getAttribute('href') || el.getAttribute('onclick') ||
               el.getAttribute('ng-href') || el.getAttribute('ui-sref') || '').trim();
    if (t) out.push((el.innerText || '').trim().slice(0, 40) + '\t' + t.slice(0, 200));
  });
  return out;
}
"""

# 多步登录（MFA）探测：密码框已消失且出现口令类可见输入位 → 返回其 CSS 路径
OTP_DETECT_JS = r"""
() => {
  function visible(el) {
    const r = el.getBoundingClientRect();
    const st = getComputedStyle(el);
    return r.width > 0 && r.height > 0 && st.visibility !== 'hidden' && st.display !== 'none';
  }
  function cssPath(el) {
    if (!(el instanceof Element)) return null;
    const parts = [];
    while (el && el.nodeType === 1 && parts.length < 8) {
      let sel = el.nodeName.toLowerCase();
      if (el.id) { parts.unshift(sel + '#' + CSS.escape(el.id)); break; }
      if (el.name) sel += '[name="' + el.name + '"]';
      const parent = el.parentNode;
      if (parent) {
        const sib = Array.from(parent.children).filter(c => c.nodeName === el.nodeName);
        if (sib.length > 1) sel += ':nth-of-type(' + (sib.indexOf(el) + 1) + ')';
      }
      parts.unshift(sel); el = parent;
    }
    return parts.join(' > ');
  }
  const pw = Array.from(document.querySelectorAll('input[type=password]')).filter(visible);
  if (pw.length) return null;                       // 仍在密码页 = 未进入第二步
  const re = /otp|onetime|twofa|2fa|mfa|验证码|口令|verif|code/i;
  const el = Array.from(document.querySelectorAll('input')).find(i =>
    visible(i) && re.test((i.name || '') + (i.id || '') + (i.placeholder || '') +
                          (i.getAttribute('aria-label') || '')));
  return el ? cssPath(el) : null;
}
"""

# 基础无头特征抹除（自动化标志位级；非完整反风控——强对抗目标如实登记 coverage）
STEALTH_JS = r"""
Object.defineProperty(navigator, 'webdriver', {get: () => undefined});
Object.defineProperty(navigator, 'languages', {get: () => ['zh-CN', 'zh', 'en']});
Object.defineProperty(navigator, 'plugins', {get: () => [1, 2, 3, 4, 5]});
window.chrome = window.chrome || { runtime: {} };
"""


def try_captcha_ocr(page, sel):
    """可选档：对验证码图片做本地 OCR（ddddocr），成功返回识别文本，失败返回空串。
    设计约束：依赖缺失/识别失败一律静默回退人工口径（exit 42），绝不阻塞主流程；
    识别值只填入表单，不写入 summary 明文（与凭据脱敏口径一致）。"""
    try:
        from ddddocr import DdddOcr  # 延迟导入：未安装时走人工口径
    except Exception:
        log("[ocr] ddddocr 未安装（pip install ddddocr），回退人工读码")
        return ""
    import re as _re
    try:
        ocr = DdddOcr(show_ad=False)
    except TypeError:
        ocr = DdddOcr()
    # 找验证码图片：常见 src/class/名含 code|captcha|yzm|verify 的 img，取密码框同表单内优先
    img_sel = page.evaluate(
        """() => {
            const re = /code|captcha|verif|yzm|验证码/i;
            const imgs = [...document.querySelectorAll('img')].filter(i => re.test(i.src + ' ' + i.className + ' ' + (i.id||'')));
            if (!imgs.length) return '';
            imgs.sort((a,b) => (b.width*b.height) - (a.width*a.height));
            imgs[0].scrollIntoView({block:'center'});
            imgs[0].setAttribute('data-jt-ocr', '1');
            return 'img[data-jt-ocr="1"]';
        }"""
    )
    if not img_sel:
        return ""
    png = page.locator(img_sel).first.screenshot()
    try:
        text = ocr.classification(png)
    except Exception:
        return ""
    text = _re.sub(r"[^0-9a-zA-Z]", "", (text or "").strip())
    return text if 3 <= len(text) <= 8 else ""


def main():
    ap = argparse.ArgumentParser(description="browser_login.py — 真实浏览器合规登录与会话捕获")
    ap.add_argument("--url", required=True, help="登录页 URL")
    ap.add_argument("--out", required=True, help="产物输出目录（建议 evidence/browser-login）")
    ap.add_argument("--user", default="", help="用户名（允许明文；密码严禁走 argv）")
    ap.add_argument("--password-env", default="JT_PASS", help="存放密码的环境变量名（默认 JT_PASS）")
    ap.add_argument("--profile", default="", help="选择器覆盖 JSON 文件 {user,pass,code,submit,successMarker}")
    ap.add_argument("--user-sel", default="", help="用户名输入框 CSS 选择器（覆盖自动探测）")
    ap.add_argument("--pass-sel", default="", help="密码输入框 CSS 选择器")
    ap.add_argument("--code-sel", default="", help="验证码输入框 CSS 选择器")
    ap.add_argument("--submit-sel", default="", help="提交按钮 CSS 选择器")
    ap.add_argument("--captcha", default="", help="验证码值（人工读码后传入；本工具不自动识别）")
    ap.add_argument("--captcha-ocr", action="store_true", help="可选：验证码可见且未提供 --captcha 时，先尝试本地 OCR（ddddocr，需已安装）；识别失败仍走 exit 42 人工读码。默认关闭（合规口径默认人工读码）")
    ap.add_argument("--otp-env", default="", help="多步登录 OTP 口令的环境变量名（如 JT_OTP）；提交后出现口令输入位时自动注入，未配置时 exit 45 转人工")
    ap.add_argument("--detect-timeout", type=float, default=10, help="登录表单探测等待秒数（SPA 慢挂载场景轮询重试，默认 10）")
    ap.add_argument("--success-marker", default="", help="登录成功判据：页面包含该文本")
    ap.add_argument("--success-url-contains", default="", help="登录成功判据：URL 包含该子串")
    ap.add_argument("--ua", default="", help="覆盖 User-Agent（默认真实 Chromium UA）")
    ap.add_argument("--proxy", default="", help="显式代理（默认剥离全部代理环境变量，目标直连）")
    ap.add_argument("--interval-sec", type=float, default=2.0, help="步骤间隔秒数（默认 2）")
    ap.add_argument("--global-timeout", type=float, default=240, help="全局看门狗秒数（默认 240）")
    ap.add_argument("--headless", dest="headless", action="store_true", default=True)
    ap.add_argument("--headed", dest="headless", action="store_false", help="有头模式（调试用，容器内需 X）")
    args = ap.parse_args()

    password = os.environ.get(args.password_env, "")
    if not password:
        log(f"FATAL: 环境变量 {args.password_env} 未设置——凭据必须经环境变量注入，禁止写入 argv/脚本")
        return EXIT_USAGE

    out = Path(args.out)
    (out / "shots").mkdir(parents=True, exist_ok=True)
    profile = {}
    if args.profile:
        profile = json.loads(Path(args.profile).read_text(encoding="utf-8"))

    browser_path = detect_browser_path()
    if not browser_path:
        log("FATAL: 未找到 chromium 可执行文件（可经 JT_BROWSER_PATH 指定）")
        return EXIT_USAGE

    from playwright.sync_api import sync_playwright, TimeoutError as PWTimeout

    secrets = [password, args.captcha]
    otp_value = os.environ.get(args.otp_env, "") if args.otp_env else ""
    if otp_value:
        secrets.append(otp_value)
    deadline = time.time() + args.global_timeout

    launch_args = ["--no-sandbox", "--disable-dev-shm-usage", "--disable-gpu",
                   "--disable-blink-features=AutomationControlled"]

    # 对目标直连：剥离代理环境变量（--proxy 显式开启除外）
    for k in PROXY_KEYS:
        os.environ.pop(k, None)
    if args.proxy:
        os.environ["http_proxy"] = os.environ["https_proxy"] = args.proxy

    ret = EXIT_USAGE
    summary = {"ok": False, "url": args.url, "artifacts": {}}

    with sync_playwright() as pw:
        browser = pw.chromium.launch(executable_path=browser_path, headless=args.headless,
                                     args=launch_args)
        ctx = browser.new_context(ignore_https_errors=True,
                                  record_har_path=str(out / "network.har"),
                                  user_agent=args.ua or None, locale="zh-CN")
        ctx.add_init_script(STEALTH_JS)
        page = ctx.new_page()

        try:
            page.goto(args.url, wait_until="domcontentloaded", timeout=30000)
            time.sleep(args.interval_sec)
            page.screenshot(path=str(out / "shots" / "login.png"))
            summary["artifacts"]["login_shot"] = "shots/login.png"

            # 表单探测（SPA 慢挂载场景轮询重试，窗口 --detect-timeout）
            det_deadline = time.time() + args.detect_timeout
            det = page.evaluate(DETECT_JS)
            while not det.get("pass") and time.time() < det_deadline:
                time.sleep(1)
                det = page.evaluate(DETECT_JS)
            sel = {
                "user": args.user_sel or profile.get("user") or det["user"],
                "pass": args.pass_sel or profile.get("pass") or det["pass"],
                "code": args.code_sel or profile.get("code") or det["code"],
                "submit": args.submit_sel or profile.get("submit") or det["submit"],
            }
            summary["selectors"] = {k: v for k, v in sel.items() if v}
            summary["page_title"] = det.get("title", "")
            log(f"[detect] user={sel['user']} pass={sel['pass']} code={sel['code']} submit={sel['submit']}")

            if not sel["pass"]:
                (out / "login-page.html").write_text(page.content(), encoding="utf-8")
                summary["error"] = "未探测到密码输入框——非标准登录页，请人工确认或用 --profile 指定选择器"
                ret = EXIT_NAV
            elif (profile.get("forceCaptcha") or det.get("codeVisible")) and not args.captcha:
                ocr_val = try_captcha_ocr(page, sel) if args.captcha_ocr else ""
                if ocr_val:
                    args.captcha = ocr_val
                    log(f"[ocr] 验证码本地识别成功（长度 {len(ocr_val)}），自动填入；不回显明文")
                else:
                    # 验证码人机协同：可见且未提供值/OCR 未命中 → 退出 42，由智能体 request_user_input 转人工
                    summary["error"] = "验证码可见且未提供 --captcha（或 OCR 未命中）——需人工读码（request_user_input）后重试"
                    ret = EXIT_CAPTCHA
            else:
                if sel["user"] and args.user:
                    page.fill(sel["user"], args.user)
                page.fill(sel["pass"], password)
                if args.captcha and sel["code"]:
                    page.fill(sel["code"], args.captcha)
                time.sleep(max(0.5, args.interval_sec / 2))

                url_before = page.url
                if sel["submit"]:
                    try:
                        page.click(sel["submit"], timeout=8000)
                    except PWTimeout:
                        page.evaluate("() => { const f = document.querySelector('form'); if (f) f.submit(); }")
                else:
                    page.evaluate("() => { const f = document.querySelector('form'); if (f) f.submit(); }")

                # 成功判定（三选一，窗口 20s）：marker 文本 / URL 判据 / 密码框消失
                # 多步登录（MFA-OTP）：密码框消失后出现口令输入位 → --otp-env 自动注入或 exit 45 转人工
                otp_done = False
                otp_pending = False
                marker = args.success_marker or profile.get("successMarker") or ""
                success = False
                try:
                    page.wait_for_load_state("domcontentloaded", timeout=20000)
                except PWTimeout:
                    pass
                for _ in range(20):
                    if time.time() > deadline:
                        break
                    time.sleep(1)
                    content = ""
                    try:
                        content = page.content()
                    except Exception:
                        pass
                    if not otp_done:
                        otp_sel = page.evaluate(OTP_DETECT_JS)
                        if otp_sel:
                            if otp_value:
                                page.fill(otp_sel, otp_value)
                                try:
                                    page.keyboard.press("Enter")
                                except Exception:
                                    pass
                                otp_done = True
                                summary["mfa_step"] = "otp-auto"
                                time.sleep(max(1.0, args.interval_sec))
                                continue
                            page.screenshot(path=str(out / "shots" / "mfa-otp.png"))
                            summary["artifacts"]["mfa_shot"] = "shots/mfa-otp.png"
                            summary["error"] = ("多步登录需 OTP 口令——--otp-env 未配置或为空；"
                                                "转人工（request_user_input）或配置后重试")
                            summary["final_url"] = page.url
                            otp_pending = True
                            break
                    if marker and marker in content:
                        success = True
                        break
                    if args.success_url_contains and args.success_url_contains in page.url:
                        success = True
                        break
                    if page.url != url_before:
                        try:
                            gone = page.locator("input[type=password]").first.is_visible()
                        except Exception:
                            gone = True
                        if not gone:
                            success = True
                            break
                time.sleep(args.interval_sec)

                if otp_pending:
                    ret = EXIT_OTP
                elif not success:
                    page.screenshot(path=str(out / "shots" / "login-failed.png"))
                    (out / "login-failed.html").write_text(page.content(), encoding="utf-8")
                    summary["error"] = f"登录未确认（最终 URL: {page.url}）——见 login-failed.html/png 诊断"
                    summary["final_url"] = page.url
                    ret = EXIT_LOGIN
                else:
                    # ---- 登录成功，抓取 CLI 接管所需全部材料 ----
                    page.screenshot(path=str(out / "shots" / "postlogin.png"))
                    (out / "postlogin.html").write_text(page.content(), encoding="utf-8")
                    cookies = ctx.cookies()
                    write_netscape(cookies, out / "cookies.txt")
                    (out / "cookies.json").write_text(
                        json.dumps(cookies, ensure_ascii=False, indent=2), "utf-8")
                    summary["artifacts"].update({
                        "cookies": "cookies.txt", "postlogin_html": "postlogin.html",
                        "postlogin_shot": "shots/postlogin.png"})
                    summary["cookie_names"] = [c["name"] for c in cookies]

                    storage = page.evaluate(
                        "() => ({ origin: location.origin,"
                        " localStorage: Object.fromEntries(Object.entries(localStorage)),"
                        " sessionStorage: Object.fromEntries(Object.entries(sessionStorage)) })")
                    (out / "storage.json").write_text(
                        json.dumps(storage, ensure_ascii=False, indent=2), "utf-8")
                    summary["artifacts"]["storage"] = "storage.json"
                    summary["storage_keys"] = {k: sorted(v.keys()) for k, v in
                                               (("localStorage", storage.get("localStorage", {})),
                                                ("sessionStorage", storage.get("sessionStorage", {})))}

                    links = page.evaluate(LINKS_JS)
                    html = page.content()
                    # 页面源码中的路径型字符串（端点候选，对齐 S4 的 JS 端点提取口径）
                    paths = sorted(set(re.findall(r'"(/[a-zA-Z0-9_/.-]{3,80})"', html)))
                    (out / "postlogin-links.txt").write_text(
                        "# DOM 链接/按钮\n" + "\n".join(links) +
                        "\n\n# 页面源码路径候选\n" + "\n".join(paths) + "\n", encoding="utf-8")
                    summary["artifacts"]["links"] = "postlogin-links.txt"
                    summary["links_count"] = len(links) + len(paths)
                    summary["final_url"] = page.url
                    summary["ok"] = True
                    ret = EXIT_OK
        except PWTimeout as e:
            summary["error"] = f"导航/加载超时: {e}"
            ret = EXIT_NAV
        except Exception as e:
            summary["error"] = f"{type(e).__name__}: {e}"
            ret = EXIT_NAV
        finally:
            (out / "summary.json").write_text(
                json.dumps(summary, ensure_ascii=False, indent=2), "utf-8")
            try:
                ctx.close()   # 关闭后才落盘 HAR
                browser.close()
            except Exception:
                pass

    # HAR 脱敏：密码/验证码明文替换（若站点本身加密则 HAR 中本无明文，双保险）
    har_path = out / "network.har"
    if har_path.exists():
        har = har_path.read_text(encoding="utf-8", errors="replace")
        har_path.write_text(scrub(har, secrets), encoding="utf-8")

    print(json.dumps(summary, ensure_ascii=False))
    return ret


if __name__ == "__main__":
    sys.exit(main())
